-- Retroactivo: reemplaza el area de TODAS las atenciones ya registradas que
-- coincidan (case-insensitive) con una actividad del catálogo. Las que no
-- coinciden (casos ambiguos, texto libre de 360 Laboral, etc.) quedan
-- exactamente como estaban.
update atenciones a
set area = m.area
from actividad_area m
where a.area is not null
  and upper(trim(a.area)) = upper(trim(m.actividad))
  and a.area is distinct from m.area;
